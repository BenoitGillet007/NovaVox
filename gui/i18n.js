// Langue actuellement affichée — mise à jour par applyTranslations() (voir
// script.js, appelée à l'initialisation et à chaque changement de langue).
let currentUiLanguage = "fr";

// Traduit une clé dans la langue courante, avec repli sur le français puis
// sur la clé elle-même si vraiment introuvable — ne doit jamais faire
// planter l'affichage pour une clé pas encore traduite.
function t(key) {
  const dict = TRANSLATIONS[currentUiLanguage] || TRANSLATIONS.fr;
  return dict[key] ?? TRANSLATIONS.fr[key] ?? key;
}

// Applique les traductions à tous les éléments marqués data-i18n (texte) /
// data-i18n-title (attribut title) / data-i18n-placeholder (attribut
// placeholder) — appelée à l'initialisation et à chaque changement de
// langue (voir onUiLanguageChange dans script.js).
function applyTranslations(lang) {
  if (lang && TRANSLATIONS[lang]) currentUiLanguage = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}
